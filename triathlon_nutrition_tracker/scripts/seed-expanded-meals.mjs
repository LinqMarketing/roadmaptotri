async function seedMeals() {
  const connection = await pool.getConnection();
  try {
    // Delete existing meals to avoid duplicates
    await connection.execute('DELETE FROM mealRecipes');

    // Insert all meals
    for (const meal of expandedMeals) {
      await connection.execute(
        `INSERT INTO mealRecipes (name, description, category, caloriesPerServing, carbs, protein, fats, servingSize, prepTime, ingredients)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
        [
          meal.name,
          meal.description,
          meal.category,
          meal.caloriesPerServing,
          meal.carbs,
          meal.protein,
          meal.fats,
          meal.servingSize,
          meal.prepTime,
          meal.ingredients,
        ]
      );
    }

    console.log(`✅ Successfully seeded ${expandedMeals.length} meal recipes`);
  } catch (error) {
    console.error('❌ Error seeding meals:', error);
    throw error;
  } finally {
    await connection.release();
    await pool.end();
  }
}

seedMeals();
